CREATE DATABASE ecommerce;

USE ecommerce;

CREATE TABLE Customers(
    CUSTOMER_ID INT PRIMARY KEY AUTO_INCREMENT,
    FIRST_NAME VARCHAR(128) NOT NULL,
    LAST_NAME VARCHAR(128),
    PASSWORD VARCHAR(128) NOT NULL,
    EMAIL VARCHAR(256) NOT NULL
);

CREATE TABLE Shipping(
    SHIPPING_ID INT PRIMARY KEY AUTO_INCREMENT,
    ADDRESS_1 VARCHAR(120) NOT NULL,
    ADDRESS_2 VARCHAR(120),
    CITY VARCHAR(120) NOT NULL,
    PROVINCE VARCHAR(60),
    COUNTRY VARCHAR(60) NOT NULL,
    ZIP_CODE VARCHAR(10) NOT NULL
);

CREATE TABLE Products(
    PRODUCT_ID INT PRIMARY KEY AUTO_INCREMENT,
    NAME VARCHAR(256) NOT NULL,
    MANF VARCHAR(256),
    CATEGORY VARCHAR(64),
    DESCRIPTION MEDIUMTEXT,
    IMAGE BLOB,
    PRICE DECIMAL(64,2) CHECK (PRICE >= 0.0)
);

CREATE TABLE Reviews(
    CUSTOMER_ID INT,
    PRODUCT_ID INT,
    PRIMARY KEY(CUSTOMER_ID, PRODUCT_ID),
    STAR_RATING INT(1) NOT NULL NOT NULL CHECK (STAR_RATING >= 0 AND STAR_RATING <= 5),
    REVIEW MEDIUMTEXT,

    CONSTRAINT FK_CUSTOMER_REVIEW
        FOREIGN KEY(CUSTOMER_ID)
        REFERENCES Customers(CUSTOMER_ID),

    CONSTRAINT FK_PRODUCT_REVIEW
        FOREIGN KEY(PRODUCT_ID)
        REFERENCES Products(PRODUCT_ID)
);

CREATE TABLE Orders(
    ORDER_ID INT AUTO_INCREMENT,
    CUSTOMER_ID INT,
    SHIPPING_ID INT,
    PRIMARY KEY(ORDER_ID, CUSTOMER_ID, SHIPPING_ID),
    ORDER_DATE DATETIME NOT NULL,
    TOTAL_AMOUNT DECIMAL(64,2) CHECK (TOTAL_AMOUNT >= 0.0),
    ORDER_STATUS INT(1) NOT NULL,

    CONSTRAINT FK_CUSTOMER_ORDER
        FOREIGN KEY(CUSTOMER_ID)
        REFERENCES Customers(CUSTOMER_ID)
);

CREATE TABLE OrderDetails(
    ORDER_ID INT,
    PRODUCT_ID INT,
    PRIMARY KEY(ORDER_ID, PRODUCT_ID),
    QUANTITY INT NOT NULL CHECK (QUANTITY >= 0.0),
    PURCHASE_PRICE DECIMAL(64,2) CHECK (PURCHASE_PRICE >= 0.0),

    CONSTRAINT FK_ORDER_ORDERDETAIL
        FOREIGN KEY(ORDER_ID)
        REFERENCES Orders(ORDER_ID),

    CONSTRAINT FK_PRODUCT_ORDERDETAIL
        FOREIGN KEY(PRODUCT_ID)
        REFERENCES Products(PRODUCT_ID)
);

CREATE TABLE Inventory(
    PRODUCT_ID INT PRIMARY KEY,
    IN_STOCK_QUANTITY INT(64) NOT NULL CHECK (IN_STOCK_QUANTITY >= 0.0),

    CONSTRAINT FK_PRODUCT_INVENTORY
        FOREIGN KEY(PRODUCT_ID)
        REFERENCES Products(PRODUCT_ID)
);